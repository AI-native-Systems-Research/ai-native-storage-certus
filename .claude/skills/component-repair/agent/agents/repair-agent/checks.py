"""Anti-gaming checks that gate_policy.yaml cannot express. They can only add failures.

gate_policy.yaml protects the property bundles, the specs, the proof crate's configuration and
the Kani harnesses, and forbids status/_scored_by text. These checks add, against the worktree's
base revision (read from git, so the session cannot tamper with the reference):

- every obligation's `statement`, `source` and `traces` hash is unchanged, in every component;
- every `verify_` / `refute_` / `lemma_` function in a proof crate at base still exists and is
  byte-identical (attributes, contract, body); new proof functions may be ADDED;
- no trust escape is added to a proof crate (`#[trusted]`, `requires(false)`, `assume`);
- no test is switched off in component source (`#[ignore]`);
- changed files stay inside the writable paths (components/**/src/**, verif-creusot/src/**),
  apart from regenerated proof artefacts, Cargo.lock, the hand-off report under `.repair/`, and
  the `components/<c>/creusot` toolchain link the engine places in the worktree.

`obligation_hashes(worktree)` is also used by handlers.py to record the hashes in the ledger.
"""
from __future__ import annotations

import hashlib
import json
import re
import subprocess
from pathlib import Path, PurePosixPath
from typing import Dict, List, Optional, Tuple

import yaml

BUNDLE = re.compile(r"^components/([^/]+)/verif/unified_properties\.yaml\Z")
PROOF_SRC = re.compile(r"^components/([^/]+)/verif-creusot/src/.+\.rs\Z")
WRITABLE = (re.compile(r"^components/.+/src/"),)
TOOL_OUTPUT = (
    re.compile(r"^components/[^/]+/verif-creusot/verif/"),  # regenerated by every proof run
    re.compile(r"(^|/)Cargo\.lock\Z"),
)
HANDOFF = re.compile(r"^\.repair/[A-Za-z0-9_.-]+\Z")
TOOLCHAIN_LINK = re.compile(r"^components/[^/]+/creusot\Z")
REPAIR_TEST = re.compile(r"^components/[^/]+/src/(?:.+/)?repair_test_[A-Za-z0-9_]+\.rs\Z")
HASHED_FIELDS = ("statement", "source", "traces")
PROOF_FN = re.compile(r"^(?:pub(?:\([^)\n]*\))?\s+)?(?:(?:const|unsafe|async)\s+)*fn\s+((?:verify|refute|lemma)_[A-Za-z0-9_]*)\b",
                      re.MULTILINE)
TRUST_ESCAPES = re.compile(
    r"#\[\s*(?:creusot::)?trusted\b|#\[\s*requires\s*\(\s*false\s*\)\s*\]|\bassume\s*!?\s*[\(\{]"
)
IGNORED_TEST = re.compile(r"#\[\s*ignore\b")


def _git(cwd: Path, *args: str) -> Tuple[int, str]:
    proc = subprocess.run(["git", *args], cwd=str(cwd), capture_output=True, text=True)
    return proc.returncode, proc.stdout


def _at_base(worktree, relative: str) -> Optional[str]:
    code, out = _git(Path(worktree.path), "show", f"{worktree.base}:{relative}")
    return out if code == 0 else None


def _now(worktree, relative: str) -> Optional[str]:
    path = Path(worktree.path) / relative
    return path.read_text(encoding="utf-8", errors="replace") if path.is_file() else None


def _base_files(worktree, pattern: "re.Pattern[str]") -> List[str]:
    code, out = _git(Path(worktree.path), "ls-tree", "-r", "--name-only", worktree.base, "--", "components")
    return [line for line in out.splitlines() if pattern.match(line)] if code == 0 else []


# ---- obligation hashes -------------------------------------------------------------------------

def _obligations(text: Optional[str]) -> Dict[str, str]:
    """id -> sha256 of its statement, source and traces (canonical JSON)."""
    if text is None:
        return {}
    try:
        data = yaml.safe_load(text) or {}
    except yaml.YAMLError:
        return {"<unparseable>": "unparseable"}
    hashes = {}
    for prop in data.get("properties") or [] if isinstance(data, dict) else []:
        if isinstance(prop, dict) and prop.get("id"):
            fields = {name: prop.get(name) for name in HASHED_FIELDS}
            canonical = json.dumps(fields, sort_keys=True, default=str, ensure_ascii=False)
            hashes[str(prop["id"])] = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
    return hashes


def obligation_hashes(worktree, ids: Optional[List[str]] = None) -> Dict[str, Dict[str, Optional[str]]]:
    """{bundle path: {obligation id: {"base": hash, "now": hash}}} for every bundle at base,
    restricted to `ids` when given."""
    report: Dict[str, Dict[str, Optional[str]]] = {}
    for relative in _base_files(worktree, BUNDLE):
        before, after = _obligations(_at_base(worktree, relative)), _obligations(_now(worktree, relative))
        for oid, digest in before.items():
            if ids is None or oid in ids:
                report.setdefault(relative, {})[oid] = {"base": digest, "now": after.get(oid)}
    return report


def _obligation_failures(worktree) -> List[str]:
    failures = []
    for relative, entries in obligation_hashes(worktree).items():
        for oid, pair in entries.items():
            if pair["now"] is None:
                failures.append(f"{relative}: obligation {oid} was removed; obligations are frozen")
            elif pair["now"] != pair["base"]:
                failures.append(f"{relative}: obligation {oid} changed its statement, source or traces "
                                "(hash differs from base); fix the code, never the obligation")
    return failures


# ---- proof functions ---------------------------------------------------------------------------

CHAR_LITERAL = re.compile(r"'(?:\\(?:x[0-9a-fA-F]{2}|u\{[0-9a-fA-F]+\}|.)|[^\\'\n])'")


def top_level_items(source: str) -> List[str]:
    """Split Rust source into top-level items, each with its attributes and doc comments.

    Tracks bracket depth outside strings, comments and char literals; an item ends at a `}` or
    `;` that returns to depth 0. Plain `//` comment lines and blank lines before an item are not
    part of it (section banners may change); `///` doc comments and attributes are."""
    items, start, depth, i, n = [], 0, 0, 0, len(source)
    while i < n:
        c = source[i]
        if source.startswith("//", i):
            end = source.find("\n", i)
            i = n if end < 0 else end
            continue
        if source.startswith("/*", i):
            level, i = 1, i + 2
            while i < n and level:
                if source.startswith("/*", i):
                    level, i = level + 1, i + 2
                elif source.startswith("*/", i):
                    level, i = level - 1, i + 2
                else:
                    i += 1
            continue
        if c == "r" and re.match(r'r#*"', source[i:i + 260]) and (i == 0 or not (source[i - 1].isalnum() or source[i - 1] == "_")):
            hashes = len(re.match(r"r(#*)", source[i:]).group(1))
            close = '"' + "#" * hashes
            end = source.find(close, i + 2 + hashes)
            i = n if end < 0 else end + len(close)
            continue
        if c == '"':
            i += 1
            while i < n and source[i] != '"':
                i += 2 if source[i] == "\\" else 1
            i += 1
            continue
        if c == "'":
            m = CHAR_LITERAL.match(source, i)
            i = m.end() if m else i + 1
            continue
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
            if depth == 0 and c == "}":
                items.append(source[start:i + 1])
                start = i + 1
        elif c == ";" and depth == 0:
            items.append(source[start:i + 1])
            start = i + 1
        i += 1
    return [_strip_leading_comments(item) for item in items]


def _strip_leading_comments(item: str) -> str:
    lines = item.splitlines()
    while lines and (not lines[0].strip() or (lines[0].lstrip().startswith("//")
                                              and not lines[0].lstrip().startswith("///"))):
        lines.pop(0)
    return "\n".join(line.rstrip() for line in lines)


def proof_functions(source: str) -> Dict[str, str]:
    """name -> full item text for every top-level verify_/refute_/lemma_ function."""
    found = {}
    for item in top_level_items(source):
        # A top-level fn starts its line; fns inside impl/mod/trait blocks are indented.
        m = PROOF_FN.search(item)
        if m:
            found[m.group(1)] = item
    return found


def _proof_function_failures(worktree) -> List[str]:
    failures = []
    for relative in _base_files(worktree, PROOF_SRC):
        before = proof_functions(_at_base(worktree, relative) or "")
        if not before:
            continue
        now_text = _now(worktree, relative)
        after = proof_functions(now_text or "")
        for name, text in sorted(before.items()):
            if name not in after:
                failures.append(f"{relative}: proof function {name} existed at base and is gone; "
                                "existing verify_/refute_/lemma_ functions are frozen (add new ones instead)")
            elif after[name] != text:
                failures.append(f"{relative}: proof function {name} existed at base and was changed; "
                                "its attributes, contract and body must stay byte-identical")
    return failures


# ---- added text and paths ----------------------------------------------------------------------

def _is_toolchain_link(worktree, relative: str) -> bool:
    path = Path(worktree.path) / relative
    return bool(TOOLCHAIN_LINK.match(relative)) and path.is_symlink()


def extra_checks(workdir: Path, worktree: Optional[object]) -> List[str]:
    """Inspect the real diff against base; without a worktree there is no diff and nothing to add."""
    failures: List[str] = []
    if worktree is None:
        return failures
    for relative, added in worktree.changes():
        path = PurePosixPath(relative).as_posix()
        if PROOF_SRC.match(path) and TRUST_ESCAPES.search(added):
            failures.append(f"{path} adds a trust escape (#[trusted], requires(false) or assume); "
                            "a proof that assumes its way through is not a proof")
        if path.startswith("components/") and "/src/" in path and path.endswith(".rs") \
                and not PROOF_SRC.match(path) and IGNORED_TEST.search(added):
            failures.append(f"{path} adds #[ignore]; tests may not be switched off")
        if REPAIR_TEST.match(path) and (Path(workdir) / path).is_file() and "#[test]" not in added:
            failures.append(f"{path} is a repair test file without any #[test] function")
        allowed = (any(p.match(path) for p in WRITABLE) or any(p.match(path) for p in TOOL_OUTPUT)
                   or HANDOFF.match(path) or _is_toolchain_link(worktree, path))
        if not allowed:
            failures.append(f"{path} is outside the writable paths "
                            "(components/**/src/**, components/**/verif-creusot/src/**, .repair/)")
    failures += _obligation_failures(worktree)
    failures += _proof_function_failures(worktree)
    return failures
