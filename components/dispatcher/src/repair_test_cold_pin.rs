/// The component, its `IDispatcher`, and the mocks it is wired to.
type Fixture = (
    Arc<DispatcherComponent>,
    Arc<dyn IDispatcher + Send + Sync>,
    Arc<MapDm>,
    Arc<PoolMt>,
    Arc<HookGpu>,
);

/// A memory-tier-only dispatcher wired to the mocks above.
fn setup() -> Fixture {
    let dm = Arc::new(MapDm::default());
    let mt = Arc::new(PoolMt::new(1024 * 1024));
    let gpu = Arc::new(HookGpu::default());
    let c = DispatcherComponent::new_default();
    c.dispatch_map
        .connect(Arc::clone(&dm) as Arc<dyn IDispatchMap + Send + Sync>)
        .unwrap();
    c.logger.connect(Arc::new(QuietLogger)).unwrap();
    c.gpu_services
        .connect(Arc::clone(&gpu) as Arc<dyn IGpuServices + Send + Sync>)
        .unwrap();
    c.memory_tier
        .connect(Arc::clone(&mt) as Arc<dyn IMemoryTier + Send + Sync>)
        .unwrap();
    let d = query_interface!(c, IDispatcher).unwrap();
    d.initialize(DispatcherConfig {
        data_pci_addrs: vec!["0000:02:00.0".to_string()],
        ..Default::default()
    })
    .unwrap();
    (c, d, dm, mt, gpu)
}

/// What a concurrent `remove` saw and left behind, observed mid-promotion.
#[derive(Debug, Default)]
struct MidPromotion {
    remove_result: Option<String>,
    entry_present: bool,
    slot_present: bool,
}

#[test]
fn concurrent_remove_cannot_delete_entry_during_cold_promotion() {
    const KEY: CacheKey = 1;
    let (_c, d, dm, mt, gpu) = setup();

    // An SSD-only (BlockDevice) entry, as left by a demotion or recovery.
    dm.recover_extent(KEY, 0x1000, 1).unwrap();

    let seen = Arc::new(Mutex::new(MidPromotion::default()));
    {
        let (d2, dm2, mt2, seen2) = (
            Arc::clone(&d),
            Arc::clone(&dm),
            Arc::clone(&mt),
            Arc::clone(&seen),
        );
        *gpu.on_h2d.lock().unwrap() = Some(Box::new(move || {
            // The promotion has inserted its slot and is copying it to the GPU.
            // A remove from another client runs now, to completion.
            let d3 = Arc::clone(&d2);
            let r = std::thread::spawn(move || d3.remove(KEY)).join().unwrap();
            let mut s = seen2.lock().unwrap();
            s.remove_result = Some(format!("{r:?}"));
            s.entry_present = dm2.entries.lock().unwrap().contains_key(&KEY);
            s.slot_present = mt2.contains(KEY);
        }));
    }

    let mut buf = vec![0u8; 4096];
    let h = IpcHandle {
        address: buf.as_mut_ptr(),
        size: buf.len() as u32,
    };
    let r = d.lookup(KEY, h);

    let s = seen.lock().unwrap();
    assert!(
        s.remove_result.is_some(),
        "the cold lookup never reached its slot -> GPU copy (lookup returned {r:?})"
    );
    assert!(
        s.entry_present,
        "a concurrent remove deleted the entry while its cold lookup was still promoting it \
         (remove returned {:?}, lookup returned {r:?})",
        s.remove_result
    );
    assert!(
        s.slot_present,
        "a concurrent remove freed the memory-tier slot the cold lookup was still copying from \
         (remove returned {:?}, lookup returned {r:?})",
        s.remove_result
    );
    assert!(r.is_ok(), "the cold lookup itself must succeed, got {r:?}");
    drop(s);

    d.shutdown().unwrap();
}
